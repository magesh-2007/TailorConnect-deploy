const LanguageContext = createContext()

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('tc_lang') || 'en')

  useEffect(() => {
    localStorage.setItem('tc_lang', lang)
    document.documentElement.lang = lang
  }, [lang])

  const t = (key) => {
    if (!key) return ''
    if (typeof key !== 'string') return key
    const trimmed = key.trim()
    return (
      FULL_DICTIONARY[lang]?.[key] ||
      FULL_DICTIONARY[lang]?.[trimmed] ||
      TRANSLATION_KEYS[lang]?.[key] ||
      TRANSLATION_KEYS[lang]?.[trimmed] ||
      TRANSLATION_KEYS.en?.[key] ||
      TRANSLATION_KEYS.en?.[trimmed] ||
      key
    )
  }

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, translations: TRANSLATION_KEYS, FULL_DICTIONARY }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    return { lang: 'en', setLang: () => {}, t: (k) => k, translations: TRANSLATION_KEYS, FULL_DICTIONARY }
  }
  return context
}
